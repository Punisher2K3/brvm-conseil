'use strict';
const assert=require('node:assert/strict'),m=require('./previsions.js');
assert.equal(typeof m.productionGuard,'function');
assert.equal(m.productionGuard([]).allow,false);
const records=(n,err,y=.02)=>Array.from({length:n},()=>({shadowError:err,y}));
assert.equal(m.productionGuard(records(29,0)).allow,false);
assert.equal(m.productionGuard(records(60,.01)).allow,true);
assert.equal(m.productionGuard(records(60,.021)).allow,false);
assert.equal(m.productionGuard(records(60,0,0)).allow,false);
const mixed=[...records(20,.001),...records(20,.025),...records(20,.025)];
assert.equal(m.productionGuard(mixed).allow,false);
const recovery=[...records(60,.05),...records(60,.005)];
assert.equal(m.productionGuard(recovery).allow,true);
let price=1000;
const history=Array.from({length:200},(_,i)=>{const previous=price;price*=1+.008*Math.sin(i*.7);return {symbol:'T',date:new Date(Date.UTC(2025,0,1+i)).toISOString().slice(0,10),close:price,reference:price,previous,opening:previous,volume:100+i%13,value:(100+i%13)*price*.997};});
const a=h=>({symbol:'T',history:h,asOf:h.at(-1).date});
const full=m.forecast(a(history),{trace:true}),prefix=m.forecast(a(history.slice(0,160)),{trace:true});
const decision=full.trace.find(r=>r.origin===prefix.date);
assert.equal(decision.predicted,prefix.expectedReturn);assert.equal(decision.selected,prefix.modelId);
assert.ok(full.trace.every(r=>Number.isFinite(r.shadowError)));
assert.ok(full.selectionGuard&&full.selectionGuard.n<=60);
console.log('Protection : historique insuffisant, avantage, sous-périodes, récupération et absence de données futures vérifiés.');
